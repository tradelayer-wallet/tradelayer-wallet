import Fastify, { FastifyInstance, FastifyServerOptions } from 'fastify';
import { handleRoutes } from './routes';
import { RpcClient } from 'tl-rpc';
import { SocketService } from './services/socket.service';
import { IOBSocketServiceOptions, OBSocketService } from './services/ob-sockets.service';
import { authTokensMatch, isLoopbackHostHeader } from './utils/auth.util';
import * as killPort from 'kill-port';

export class FastifyServer {
    private _server: FastifyInstance;
    public rpcClient: RpcClient;
    public rpcPort: number;
    public mainSocketService: SocketService;
    public obSocketService: OBSocketService;

    public relayerApiUrl: string | null = null;

    constructor(
        private port: number, 
        options: FastifyServerOptions,
        private safeClose: () => void,
        private authToken: string,
    ) {
        this._server = Fastify(options);
        this.mainSocketService = new SocketService();
        // Two checks on EVERY request that reaches this hook (the server has
        // no public routes; everything proxies node RPC or key handling):
        //
        // 1. DNS-rebinding mitigation: the Host header must be loopback.
        // 2. Per-session auth: the random token generated by the Electron main
        //    process must be in the `x-tl-auth` header (issue #45, C1).
        //
        // Neither check depends on the path. An earlier version guarded only
        // `/keys/*` and `/api/*` by matching the raw request target, which an
        // absolute-form target (`POST http://attacker.example/api/rpc-call`)
        // bypassed while the router still matched the route. Do not add a
        // path-based exemption here.
        //
        // socket.io traffic does not reach this hook: engine.io answers
        // origin-form `/socket.io/` requests on the raw HTTP server first, and
        // SocketService enforces Host + Origin + token for them.
        //
        // Scope: Fastify's default `onBadUrl` handler answers malformed request
        // targets (`GET http://localhost` with no path, `OPTIONS *`) with 404
        // before any hook runs. No route is reachable through those.
        this._server.addHook('onRequest', (request, reply, next) => {
            if (!isLoopbackHostHeader(request.headers.host)) {
                reply.status(403).send({ error: 'Forbidden Host header' });
                return;
            }
            const token = request.headers['x-tl-auth'];
            if (authTokensMatch(token, this.authToken)) return next();
            reply.status(403).send({ error: 'Forbidden: missing or invalid auth token' });
        });
    }

    get server() {
        return this._server
    }

    start() {
        handleRoutes(this.server);
        this.mainSocketService.init(this.server, this.authToken);
        // Bind to loopback only. Fastify v3 defaults to 0.0.0.0 when no host
        // is given, which exposed this signing/RPC API to the entire local
        // network (issue #46).
        this.server.listen(this.port, '127.0.0.1')
            .catch((error) => this.stop());
    }

    async stop() {
        if (this.rpcClient) {
            const isConnectedRes = await this.rpcClient.call('getblockchaininfo');
            const isConnected = !!isConnectedRes.data;
            if (isConnected) await this.rpcClient.call('stop');
            if (!isConnected) await killPort(this.rpcPort);
        }

        this.safeStop();
        const safeExistInterval = setInterval(() => {
            if (this.rpcClient || this.rpcPort) return;
            clearInterval(safeExistInterval);
            this.safeStop();
        }, 500);
    }

    private safeStop() {
        if (this.rpcClient || this.rpcPort) return;
        this.clearOBSocketConnection();
        this.safeClose();
        this.clearMainSocketConnection();
    }

    initOBSocketConnection(options: IOBSocketServiceOptions) {
        this.clearOBSocketConnection();
        this.obSocketService = new OBSocketService(options);
    }


    clearMainSocketConnection() {
        if (this.mainSocketService?.currentSocket) {
            this.mainSocketService?.currentSocket.offAny();
            this.mainSocketService?.currentSocket.disconnect();
        }
        this.mainSocketService = null;
    }

    clearOBSocketConnection() {
        if (this.obSocketService?.socket) {
            this.obSocketService.socket.offAny();
            this.obSocketService.socket.disconnect();
        }
        this.obSocketService = null;
    }
}
